-- Приём ключей не блокируется следующей бронью.
--
-- Найдено 23.11 при проверке просроченного возврата. Поездка #97 вернулась на
-- два дня позже планового, а на этот автомобиль за время ожидания завели бронь
-- на сегодня. Триггер при закрытии растягивал занятый интервал #97 до
-- фактического возврата — и он накрывал ту бронь. Postgres отказывал кодом
-- 23P01, рецепция получала «не получилось сохранить», поездка оставалась в
-- пути, а машина — занятой. То есть ровно тот тупик, который миграция 0003
-- устраняла для досрочного возврата, только с другой стороны.
--
-- В требованиях (Э4, «Приём ключей») написано иначе: «После корректного
-- одометра доступно „Принять“ … фактическое время возврата, закрытие поездки,
-- освобождение оставшейся части брони; следующая бронь — не раньше чем через
-- 10 минут после фактического возврата». Десять минут — условие следующей
-- выдачи, а не приёма ключей. Приём ничем, кроме одометра, не обусловлен.
--
-- Решение: ограничения пересечения относятся к планам, а не к истории.
-- Закрытая поездка — факт: машина физически вернулась, занимать время она уже
-- не может. Двойная бронь при этом по-прежнему невозможна: две действующие
-- брони (booked, docs_ready, in_trip) пересечься не могут, как и раньше.
--
-- Буфер в 10 минут после фактического возврата проверяется теперь при выдаче
-- ключей (`issueKeys`) — там, где его и требуют: нельзя отдать машину, которую
-- только что приняли, пока её не осмотрели.

alter table trips drop constraint trips_car_no_overlap;

alter table trips add constraint trips_car_no_overlap
  exclude using gist (car_id with =, booking_during with &&)
  where (status <> 'closed');

alter table trips drop constraint trips_driver_no_overlap;

alter table trips add constraint trips_driver_no_overlap
  exclude using gist (driver_id with =, booking_during with &&)
  where (status <> 'closed');
