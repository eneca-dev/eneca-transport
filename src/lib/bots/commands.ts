/**
 * Команды бота Teams.
 *
 * Список команд объявлен в манифесте (`teams/manifest.template.json`), и Teams
 * показывает его под полем ввода — это и есть «кнопки-подсказки». Нажатие на
 * подсказку не особое событие: Teams отправляет боту её название обычным
 * сообщением. Поэтому названия команд и то, что здесь разбирается, должны
 * совпадать, иначе подсказка приведёт к общему ответу «вот кнопки».
 *
 * Разбор здесь без обращений к базе: это таблица слов, и ошибки в ней
 * (лишний пробел, не та форма слова) должны проверяться без приложения.
 */

export type TeamsCommand = 'my_trips' | 'new_trip' | 'help';

/**
 * Слова, по которым узнаётся команда.
 *
 * Кроме названий из манифеста — то, что человек напишет сам. «Помощь» в
 * требованиях помечена как желательная команда ботов; здесь она отвечает той
 * же карточкой с кнопками, что и приветствие.
 */
const WORDS: Record<TeamsCommand, string[]> = {
  my_trips: ['мои поездки', 'поездки', 'мои заявки', 'my trips'],
  new_trip: ['новая поездка', 'новая заявка', 'заявка', 'new trip'],
  help: [
    'помощь',
    'справка',
    'инструкция',
    'как пользоваться',
    'что ты умеешь',
    'help',
    'start',
    'меню',
  ],
};

/**
 * Привести написанное к сравнимому виду.
 *
 * Teams присылает название подсказки как есть, человек — как придётся:
 * с косой чертой от привычки к другим ботам, с точкой, с двойными пробелами
 * или с упоминанием бота в начале строки.
 */
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/<at>.*?<\/at>/g, ' ')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}

/** Какая это команда. `null` — обычное сообщение, а не команда. */
export function matchTeamsCommand(text: string): TeamsCommand | null {
  const normalized = normalize(text);

  if (normalized === '') {
    return null;
  }

  for (const [command, words] of Object.entries(WORDS) as [TeamsCommand, string[]][]) {
    if (words.includes(normalized)) {
      return command;
    }
  }

  return null;
}
